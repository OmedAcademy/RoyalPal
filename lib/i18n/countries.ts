/**
 * Turns an ISO 3166-1 alpha-2 code into its flag emoji by mapping each
 * ASCII letter to its Unicode regional-indicator symbol. Any code that
 * isn't exactly two A–Z letters (the non-ISO entities below) must supply
 * an explicit `flag` instead.
 */
function flagFromAlpha2(alpha2: string): string {
  if (!/^[A-Z]{2}$/.test(alpha2)) return "🏳️";
  const A = 0x1f1e6;
  const codePoints = [...alpha2].map((c) => A + (c.charCodeAt(0) - 65));
  return String.fromCodePoint(...codePoints);
}

